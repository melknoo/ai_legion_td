// Turns the extracted builder roster into renamed game data for shared/ and sprite mappings for client/.
// Usage: node export-fighters.mjs <builders.json> <rename.json> <sharedOut.ts> <clientOut.ts> <ninjaAssetsDir>
import fs from 'node:fs';
import path from 'node:path';

const [buildersPath, renamePath, sharedOut, clientOut, ninjaDir] = process.argv.slice(2);
if (!ninjaDir) {
  console.error('Usage: node export-fighters.mjs <builders.json> <rename.json> <sharedOut.ts> <clientOut.ts> <ninjaAssetsDir>');
  process.exit(1);
}

const builders = JSON.parse(fs.readFileSync(buildersPath, 'utf8'));
const rename = JSON.parse(fs.readFileSync(renamePath, 'utf8'));
// Further builders live in rename-parts/*.json next to the main file (same shape).
const partsDir = path.join(path.dirname(renamePath), 'rename-parts');
if (fs.existsSync(partsDir)) {
  for (const file of fs.readdirSync(partsDir).filter((f) => f.endsWith('.json')).sort()) {
    const part = JSON.parse(fs.readFileSync(path.join(partsDir, file), 'utf8'));
    Object.assign(rename.builders, part.builders);
    Object.assign(rename.fighters, part.fighters);
  }
}

const ARMOR = { none: 'unarmored', small: 'light', medium: 'medium', large: 'heavy', normal: 'fortified', fort: 'fortified', hero: 'hero' };
const ATTACK = { normal: 'normal', pierce: 'pierce', siege: 'siege', magic: 'magic', chaos: 'chaos', unknown: 'normal', hero: 'chaos' };
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const units = {};
const outBuilders = {};
const sprites = {};
for (const b of builders) {
  const rb = rename.builders[b.id];
  if (!rb) continue;
  const idOf = (orig) => {
    const r = rename.fighters[orig];
    if (!r) throw new Error(`no rename for ${orig} (${b.name})`);
    return slug(r.name);
  };
  for (const f of Object.values(b.fighters)) {
    const r = rename.fighters[f.id];
    const id = idOf(f.id);
    if (units[id]) throw new Error(`duplicate fighter id ${id} (${f.id}, ${b.name})`);
    const tier = Number(/T(\d)/.exec(f.tier ?? '')?.[1] ?? 0);
    units[id] = {
      id,
      name: r.name,
      hp: f.hp,
      armor: f.armor ?? 0,
      armorType: ARMOR[f.armorType] ?? 'medium',
      attack: {
        damage: f.damage,
        cooldownMs: Math.round((f.cooldown ?? 1) * 1000),
        range: f.range ?? 90,
        type: ATTACK[f.attackType] ?? 'normal',
      },
      moveSpeed: 270,
      radius: f.hp >= 1500 ? 28 : 22,
      goldCost: f.gold ?? 0,
      food: f.food ?? 1,
      ...(f.upgradesTo.length ? { upgradesTo: f.upgradesTo.map(idOf) } : {}),
      ...(tier ? { tier } : {}),
    };
    const monster = r.sprite.startsWith('m:');
    const folder = r.sprite.replace(/^m:/, '');
    sprites[id] = monster
      ? { kind: 'monster', folder, ...(r.hue ? { hue: r.hue } : {}) }
      : { kind: 'character', folder, ...(r.hue ? { hue: r.hue } : {}) };
  }
  outBuilders[rb.id] = { id: rb.id, name: rb.name, fighters: b.baseFighters.map(idOf) };
}

// Monster sheets are named inconsistently (SpriteSheet.png, Slime.png, ...): index them once.
const monsterDir = path.join(ninjaDir, 'Actor', 'Monster');
const monsterFiles = {};
for (const folder of fs.readdirSync(monsterDir)) {
  if (!fs.statSync(path.join(monsterDir, folder)).isDirectory()) continue;
  const file = fs.readdirSync(path.join(monsterDir, folder)).find((f) => f.endsWith('.png') && f !== 'Faceset.png');
  if (file) monsterFiles[folder] = file.replace(/\.png$/, '');
}

const header = '// Generated by tools/map-extract/export-fighters.mjs — do not edit by hand.\n';
fs.writeFileSync(
  sharedOut,
  `${header}import type { BuilderDef, UnitDef } from '../sim/types.ts';\n\n` +
    `export const FIGHTERS: Record<string, UnitDef> = ${JSON.stringify(units, null, 2)};\n\n` +
    `export const BUILDERS: Record<string, BuilderDef> = ${JSON.stringify(outBuilders, null, 2)};\n`,
);
fs.writeFileSync(
  clientOut,
  `${header}import type { SpriteSpec } from './manifest.ts';\n\n` +
    `export const FIGHTER_SPRITES: Record<string, SpriteSpec> = ${JSON.stringify(sprites, null, 2)};\n\n` +
    `export const MONSTER_FILES: Record<string, string> = ${JSON.stringify(monsterFiles, null, 2)};\n`,
);
console.log(`fighters: ${Object.keys(units).length}, builders: ${Object.keys(outBuilders).join(', ')}`);
